import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";
const read = name => readFileSync(new URL(name, import.meta.url), "utf8");
const js = read("./app.js"), html = read("./index.html"), css = read("./styles.css"), sw=read("./sw.js");
const pivot=js.lastIndexOf("init().catch(");
assert.ok(pivot>0, "app has startup code");
const sandbox={Intl, Date, crypto:{randomUUID:()=>"uuid"}, console};
vm.runInNewContext(js.slice(0,pivot)+"globalThis.TEST={parseMoney,seed,localDay};})();",sandbox,{timeout:2000});
const {parseMoney,seed,localDay}=sandbox.TEST;
assert.equal(seed.length,19);
assert.equal(parseMoney("0.34"),34);
assert.equal(parseMoney("0,25"),25);
assert.equal(parseMoney("1.50"),150);
assert.equal(34*3,102);
for(const n of ["1.234","-1","abc","1.2.3"])assert.ok(Number.isNaN(parseMoney(n)));
assert.equal(localDay("2026-10-28T01:00:00Z"),"2026-10-27");
assert.match(html,/styles.css/);
assert.match(css,/object-fit:contain/);
assert.match(css,/max-width:580px/);
assert.match(sw,/SKIP_WAITING/);
assert.match(js,/controllerchange/);
assert.match(js,/bakery|deliscias/i);
assert.match(js,/kiubo-deliscias-v1/);
console.log("KIUBO DeliScias: 14 static safety, money, catalog and update assertions passed");
